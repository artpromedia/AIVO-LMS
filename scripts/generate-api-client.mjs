#!/usr/bin/env node
/**
 * Generate `packages/api-client/src/<svc>.ts` from each
 * `packages/api-client/openapi/<svc>.json` via `openapi-typescript`,
 * then rewrite the barrel `src/index.ts` to re-export each generated
 * file as a namespace.
 *
 * Run via `pnpm api:generate`, which first runs `pnpm api:dump`.
 */
import { spawnSync } from "node:child_process";
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OPENAPI_DIR = resolve(ROOT, "packages/api-client/openapi");
const SRC_DIR = resolve(ROOT, "packages/api-client/src");

mkdirSync(SRC_DIR, { recursive: true });

const specs = readdirSync(OPENAPI_DIR)
  .filter((f) => f.endsWith(".json"))
  .sort();

if (specs.length === 0) {
  // eslint-disable-next-line no-console
  console.error(
    "No specs found in packages/api-client/openapi/. Run `pnpm api:dump` first.",
  );
  process.exit(1);
}

const services = [];

for (const file of specs) {
  const stem = basename(file, extname(file)); // e.g. "identity-svc"
  const inPath = resolve(OPENAPI_DIR, file);
  const outPath = resolve(SRC_DIR, `${stem}.ts`);

  const result = spawnSync(
    "pnpm",
    ["exec", "openapi-typescript", inPath, "-o", outPath],
    { cwd: ROOT, stdio: "inherit" },
  );
  if (result.status !== 0) {
    // eslint-disable-next-line no-console
    console.error(`openapi-typescript failed for ${file}`);
    process.exit(result.status ?? 1);
  }

  // namespace identifier: kebab-case stem → camelCase
  const ns = stem.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  services.push({ stem, ns });
  // eslint-disable-next-line no-console
  console.log(`[${stem}] wrote ${outPath}`);
}

// Rewrite the barrel.
const barrelLines = [
  "// AUTO-GENERATED by `pnpm api:generate` — do not edit by hand.",
  "// Regenerate after touching any service's route schemas.",
  "",
];
for (const { stem, ns } of services) {
  barrelLines.push(`export * as ${ns} from "./${stem}.js";`);
}
barrelLines.push("");
writeFileSync(resolve(SRC_DIR, "index.ts"), barrelLines.join("\n"));
// eslint-disable-next-line no-console
console.log(`wrote ${resolve(SRC_DIR, "index.ts")}`);
