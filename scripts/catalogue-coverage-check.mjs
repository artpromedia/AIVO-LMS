#!/usr/bin/env node
// catalogue:coverage — Wave D (G3) gate over the AUTHORITATIVE curriculum
// catalogue (curriculum-svc's bundled snapshot, per ADR-0040). The legacy
// `curriculum:coverage` gate audits the packages/skill-graphs seed system;
// THIS gate audits the catalogue that jurisdiction validation, grade
// anchoring, and the school-alignment pipeline actually serve from.
//
// Two layers:
//   1. HARD FLOOR — subjects the platform now guarantees catalogue-backed
//      (math, ela) must have ≥ MIN_SKILLS_PER_BAND skills in EVERY K–8
//      band. A regression here breaks the "serve what school teaches"
//      promise and fails the build.
//   2. RATCHET — per-(subject × band) skill counts may only grow.
//      Improvements must update the baseline in the same PR (exactly the
//      ux:matrix pattern), so coverage can never silently shrink.
//
// Outputs (generated, do not hand-edit):
//   docs/quality/catalogue-coverage.md            — human-readable table
//   docs/quality/catalogue-coverage-baseline.json — the ratchet
//
// Usage:
//   node scripts/catalogue-coverage-check.mjs            # check (CI gate)
//   node scripts/catalogue-coverage-check.mjs --update   # accept improvements
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");

const SNAPSHOT = join(
  repoRoot,
  "services/curriculum-svc/src/curriculum_svc/data/skill_graphs.json",
);
const BASELINE = join(repoRoot, "docs/quality/catalogue-coverage-baseline.json");
const DOC = join(repoRoot, "docs/quality/catalogue-coverage.md");

const K8_BANDS = ["K", "1", "2", "3", "4", "5", "6", "7", "8"];
// Subjects with a guaranteed catalogue floor (Wave D imports CCSS K–8).
const FLOOR_SUBJECTS = ["math", "ela"];
const MIN_SKILLS_PER_BAND = 15;

const update = process.argv.includes("--update");

const snapshot = JSON.parse(readFileSync(SNAPSHOT, "utf8"));
const counts = new Map(); // "subject|band" -> n
for (const s of snapshot.skills ?? []) {
  const key = `${s.subject}|${s.gradeBand}`;
  counts.set(key, (counts.get(key) ?? 0) + 1);
}

const errors = [];
const improvements = [];

// ── 1. Hard floor ───────────────────────────────────────────────────────────
for (const subject of FLOOR_SUBJECTS) {
  for (const band of K8_BANDS) {
    const n = counts.get(`${subject}|${band}`) ?? 0;
    if (n < MIN_SKILLS_PER_BAND) {
      errors.push(
        `floor: ${subject} grade ${band} has ${n} catalogue skills ` +
          `(< ${MIN_SKILLS_PER_BAND}). The school-alignment promise requires ` +
          `full K-8 coverage for ${FLOOR_SUBJECTS.join("/")}.`,
      );
    }
  }
}

// ── 2. Ratchet ──────────────────────────────────────────────────────────────
let baseline = {};
if (existsSync(BASELINE)) {
  baseline = JSON.parse(readFileSync(BASELINE, "utf8")).cells ?? {};
}
const cells = {};
for (const [key, n] of [...counts.entries()].sort()) cells[key] = n;

for (const [key, prev] of Object.entries(baseline)) {
  const now = cells[key] ?? 0;
  if (now < prev) {
    errors.push(`ratchet: ${key.replace("|", " grade ")} regressed ${prev} → ${now}.`);
  } else if (now > prev) {
    improvements.push(`${key.replace("|", " grade ")}: ${prev} → ${now}`);
  }
}
for (const key of Object.keys(cells)) {
  if (!(key in baseline)) improvements.push(`${key.replace("|", " grade ")}: new (${cells[key]})`);
}

// ── 3. Generated artifacts ──────────────────────────────────────────────────
const subjects = [...new Set([...counts.keys()].map((k) => k.split("|")[0]))].sort();
const bands = [...new Set([...counts.keys()].map((k) => k.split("|")[1]))].sort(
  (a, b) => (K8_BANDS.indexOf(a) + 99 * +(K8_BANDS.indexOf(a) < 0)) -
            (K8_BANDS.indexOf(b) + 99 * +(K8_BANDS.indexOf(b) < 0)),
);
let table = `# Curriculum catalogue coverage\n\n> GENERATED by \`scripts/catalogue-coverage-check.mjs\` — do not hand-edit.\n> Source: curriculum-svc bundled snapshot (skills per subject × grade band).\n\n| subject \\\\ band | ${bands.join(" | ")} |\n|---|${bands.map(() => "---").join("|")}|\n`;
for (const subject of subjects) {
  table += `| ${subject} | ${bands.map((b) => counts.get(`${subject}|${b}`) ?? 0).join(" | ")} |\n`;
}
table += `\nTotals: ${snapshot.skills.length} skills · ${snapshot.districts.length} districts · ${snapshot.contentPacks.length} packs.\n`;
table += `Hard floor: ${FLOOR_SUBJECTS.join(", ")} ≥ ${MIN_SKILLS_PER_BAND} skills per K-8 band.\n`;

if (update) {
  writeFileSync(
    BASELINE,
    JSON.stringify({ comment: "catalogue:coverage ratchet — counts may only grow.", cells }, null, 2) + "\n",
  );
  writeFileSync(DOC, table);
  console.log(`catalogue:coverage baseline updated (${Object.keys(cells).length} cells).`);
}

if (errors.length > 0) {
  for (const e of errors) console.error(`  ✗ ${e}`);
  console.error(`\ncatalogue:coverage FAILED with ${errors.length} error(s).`);
  process.exit(1);
}

if (!update && improvements.length > 0) {
  // Improvements are good news but must land WITH a baseline update so the
  // ratchet actually holds at the new level.
  for (const i of improvements) console.error(`  ↑ ${i}`);
  console.error(
    "\ncatalogue:coverage: coverage improved — run " +
      "`node scripts/catalogue-coverage-check.mjs --update` and commit the baseline + doc.",
  );
  process.exit(1);
}

// Doc drift guard: the committed table must match the snapshot.
if (!update) {
  const current = existsSync(DOC) ? readFileSync(DOC, "utf8") : "";
  if (current !== table) {
    console.error(
      "  ✗ docs/quality/catalogue-coverage.md is stale — run " +
        "`node scripts/catalogue-coverage-check.mjs --update` and commit.",
    );
    process.exit(1);
  }
}

console.log(
  `catalogue:coverage OK — ${snapshot.skills.length} skills across ` +
    `${subjects.length} subjects; floor (${FLOOR_SUBJECTS.join("/")} K-8 ≥ ${MIN_SKILLS_PER_BAND}) holds.`,
);
