function deepMerge(t, s){for(const[k,v]of Object.entries(s)){
  if(v&&typeof v==="object"&&!Array.isArray(v)){if(!t[k]||typeof t[k]!=="object")t[k]={};deepMerge(t[k],v);}
  else t[k]=v;}return t;}

